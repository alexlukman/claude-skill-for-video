#!/usr/bin/env python3
"""Regenerate STYLES.md (the style catalogue page) from skills/styles/catalog.json."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
cat = json.loads((ROOT / 'skills/styles/catalog.json').read_text())
by = {e['slug']: e for e in cat['styles']}
out = ['# Animation style catalogue', '',
       f'{len(cat["styles"])} entries: Alex\'s 88 style sheets (numbers 1-88) plus 13 styles from his written guide (89-101). '
       'Render any of them with `/styles` (`{"style": "<slug>"}`); entries marked with a skill are made by that skill. '
       'Generated from `skills/styles/catalog.json` by `tools/styles_doc.py`.', '',
       'Pictures of every style are in the gallery in [README.md](README.md#style-gallery).', '']
for c, name in cat['categories'].items():
    rows = [e for e in cat['styles'] if e['cat'] == c]
    out += [f'## {c}. {name}', '', '| # | Style | Kind | Looks like | Moves like | Made by |', '|---|---|---|---|---|---|']
    for e in rows:
        made = f'`/{e["route"]}`' if e.get('route') and not e.get('recipe') else '`/styles`' + (f' (or `/{e["route"]}`)' if e.get('route') else '')
        look = e['look'] if not e.get('alias') else f'Same as {by[e["alias"]]["name"]} ({by[e["alias"]]["n"]}). ' + (e['look'] if not e['look'].startswith('See') else '')
        note = f' *{e["note"]}*' if e.get('note') else ''
        out.append(f'| {e["n"]} | **{e["name"]}** `{e["slug"]}` | {e["kind"]} | {look.strip()}{note} | {e["motion"] or "-"} | {made} |')
    out.append('')
(ROOT / 'STYLES.md').write_text('\n'.join(out))
print('wrote', ROOT / 'STYLES.md')

# ---------------------------------------------------------------- README gallery (between the markers)
thumbs = {p.name.split('-', 1)[1][:-4]: p for p in sorted((ROOT / 'docs/styles').glob('*.jpg'))}
refs = {int(p.stem): p for p in (ROOT / 'docs/refs').glob('[0-9]*.jpg')}
hidden = set(json.loads((ROOT / 'docs/refs/excluded.json').read_text())) if (ROOT / 'docs/refs/excluded.json').exists() else set()
def cell(e):
    r = refs.get(e['n'])
    if r: left = f'<img src="docs/refs/{r.name}" width="210" alt="reference sheet {e["n"]}">'
    elif e['n'] in hidden: left = '<sub>Reference not shown (it has a studio character). This style uses an original character in the same look.</sub>'
    else: left = '<sub>From the written style guide (no reference sheet).</sub>'
    return (f'<td align="center" valign="top" width="50%"><b>{e["n"]}. {e["name"]}</b><br>{left} '
            f'<img src="docs/styles/{thumbs[e["slug"]].name}" width="118" alt="our render"><br><code>{e["slug"]}</code></td>')
g = ['<!-- styles-gallery:start (generated by tools/styles_doc.py) -->', '',
     'Each entry shows the reference picture (left) next to what `/styles` renders (right). Every character style has its own character.']
for c, name in cat['categories'].items():
    rows = [e for e in cat['styles'] if e['cat'] == c and e['slug'] in thumbs]
    g += ['', f'### {c}. {name}', '', '<table>']
    for i in range(0, len(rows), 2):
        g.append('<tr>' + ''.join(cell(e) for e in rows[i:i + 2]) + '</tr>')
    g.append('</table>')
g.append('<!-- styles-gallery:end -->')
readme = (ROOT / 'README.md').read_text()
a, b = readme.index('<!-- styles-gallery:start'), readme.index('<!-- styles-gallery:end -->') + len('<!-- styles-gallery:end -->')
(ROOT / 'README.md').write_text(readme[:a] + '\n'.join(g) + readme[b:])
print('updated README gallery:', len(thumbs), 'pictures')
