const GW = 5, GH = 7, GAP = 1;
function textWidth(str, px = 1) { return Math.max(0, str.length * (GW + GAP) - GAP) * px; }
// draws str with its top-left at (x, y); px = size of one font pixel
function drawText(ctx, str, x, y, color, px = 1, shadow = null) {
  str = String(str).toUpperCase();
  const pass = (ox, oy, col) => {
    ctx.fillStyle = col;
    for (let i = 0; i < str.length; i++) {
      const g = GLYPHS[str[i]] || GLYPHS['?'];
      for (let r = 0; r < GH; r++) for (let c = 0; c < GW; c++) if (g[r][c] === '#') ctx.fillRect(Math.round(x + ox + (i * (GW + GAP) + c) * px), Math.round(y + oy + r * px), px, px);
    }
  };
  if (shadow) { pass(px, 0, shadow); pass(-px, 0, shadow); pass(0, px, shadow); pass(0, -px, shadow); pass(px, px, shadow); }
  pass(0, 0, color);
}
